import mongoose from 'mongoose';

const faqKnowledgeSchema = new mongoose.Schema(
  {
    question: {
      type: String,
      required: true,
      trim: true
    },
    answer: {
      type: String,
      required: true,
      trim: true
    },
    category: {
      type: String,
      default: 'general',
      trim: true
    },
    keywords: {
      type: [String],
      default: []
    },
    isActive: {
      type: Boolean,
      default: true
    }
  },
  {
    timestamps: true
  }
);

export const FAQKnowledge = mongoose.model('FAQKnowledge', faqKnowledgeSchema);

